/* --------------------------------------------------------------- helpers */

export function atomById(g: MoleculeGraph, id: string): GraphAtom | undefined {
  return g.atoms.find((a) => a.id === id);
}

/** Sum of bond orders around an atom. Aromatic bonds count as 1.5. */
export function bondSumOf(g: MoleculeGraph, id: string): number {
  return g.bonds.reduce((s, b) => {
    if (b.a !== id && b.b !== id) return s;
    return s + (b.type === 'aromatic' ? 1.5 : b.order);
  }, 0);
}

export function sigmaCountOf(g: MoleculeGraph, id: string): number {
  return g.bonds.filter((b) => b.a === id || b.b === id).length;
}

export function piCountOf(g: MoleculeGraph, id: string): number {
  return g.bonds.reduce((s, b) => {
    if (b.a !== id && b.b !== id) return s;
    return s + (b.type === 'aromatic' ? 0.5 : Math.max(0, b.order - 1));
  }, 0);
}

/**
 * Bonds whose electron pairs are genuinely SHARED around this atom — i.e. everything
 * except dative (donated by the ligand) and ionic (transferred) bonds. This is what
 * valency, lone pairs and formal charge are computed from.
 */
export function covalentBondSumOf(g: MoleculeGraph, id: string): number {
  return g.bonds.reduce((s, b) => {
    if (b.a !== id && b.b !== id) return s;
    if (b.type === 'coordinate' || b.type === 'ionic') return s;
    return s + (b.type === 'aromatic' ? 1.5 : b.order);
  }, 0);
}

/**
 * Valency "usage" for the ceiling test. Aromatic bonds are worth 1.5 electrons
 * pairs for ELECTRON COUNTING, but a delocalised ring bond does not consume an
 * extra unit of valency — caffeine's ring nitrogen makes three σ bonds and donates
 * its lone pair, it is not four-valent.
 */
export function valenceUsageOf(g: MoleculeGraph, id: string): number {
  const aromatic = g.bonds.some((b) => (b.a === id || b.b === id) && b.type === 'aromatic');
  return aromatic ? sigmaCountOf(g, id) : covalentBondSumOf(g, id);
}

/**
 * Delocalised (aromatic) atoms need their own bookkeeping, because a ring bond is
 * worth 1.5 electron pairs — but the atom only DONATES one electron to the π system
 * (benzene C, pyridine N) or two (pyrrole N, furan O, caffeine's amide N).
 *
 *   π electrons donated = 1 when (V − charge − σ) is odd, else 2
 *   lone pairs          = (V − charge − σ − π) / 2        (pairs NOT in the π cloud)
 *   shell electrons     = 2·(σ + 1 π bond + lone pairs)
 */
export function aromaticShell(
  g: MoleculeGraph,
  id: string,
): { lp: number; shell: number; fc: number; sigma: number; pi: number } | null {
  const bonds = g.bonds.filter((b) => b.a === id || b.b === id);
  if (!bonds.some((b) => b.type === 'aromatic')) return null;
  const atom = atomById(g, id);
  if (!atom) return null;
  const V = getElement(atom.element).valenceElectrons;
  const charge = atom.charge ?? 0;
  const sigma = bonds.length;
  const remaining = V - charge - sigma;
  const pi = Math.abs(remaining % 2) === 1 ? 1 : 2;
  const lp = Math.max(0, (remaining - pi) / 2);
  return {
    lp,
    shell: 2 * lp + 2 * (sigma + 1),
    fc: V - 2 * lp - sigma - pi,
    sigma,
    pi,
  };
}

/** Number of dative (coordinate) bonds touching this atom. */
export function coordinateCountOf(g: MoleculeGraph, id: string): number {
  return g.bonds.filter((b) => b.type === 'coordinate' && (b.a === id || b.b === id)).length;
}

export function neighboursOf(g: MoleculeGraph, id: string): string[] {
  const out: string[] = [];
  for (const b of g.bonds) {
    if (b.a === id) out.push(b.b);
    else if (b.b === id) out.push(b.a);
  }
  return out;
}

export function getBond(g: MoleculeGraph, a: string, b: string): GraphBond | undefined {
  return g.bonds.find((x) => (x.a === a && x.b === b) || (x.a === b && x.b === a));
}

export function isMetal(symbol: string): boolean {
  return getElement(symbol).isMetal;
}

/* ------------------------------------------------------- molecular formula */

/** Hill notation: C first, H second, then all others alphabetically. */
export function hillFormula(counts: Record<string, number>): string {
  const parts: string[] = [];
  const c = counts.C;
  if (c) parts.push(c > 1 ? `C${c}` : 'C');
  const h = counts.H;
  if (h) parts.push(h > 1 ? `H${h}` : 'H');
  Object.keys(counts)
    .filter((s) => s !== 'C' && s !== 'H')
    .sort()
    .forEach((s) => parts.push(counts[s] > 1 ? `${s}${counts[s]}` : s));
  return parts.join('');
}

/** Structural-ish formula, e.g. "CH3CH2OH" — falls back to Hill. */
export function structuralFormula(g: MoleculeGraph): string {
  if (g.atoms.length === 0) return '';
  const groups: Record<string, number> = {};
  for (const a of g.atoms) groups[a.element] = (groups[a.element] ?? 0) + 1;
  return hillFormula(groups);
}

export function molarMass(g: MoleculeGraph): number {
  return g.atoms.reduce((m, a) => m + getElement(a.element).mass, 0);
}

